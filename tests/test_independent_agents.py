class IndependentAgentTests(unittest.TestCase):
    def setUp(self):
        fixtures.IntakeTests.setUp(self)
        self.app.config['INDEPENDENT_AGENTS_ENABLED'] = True
        self.api = self.app.test_client()

    def tearDown(self):
        self.temp.cleanup()

    def register(self):
        result = self.api.post('/api/v1/independent-agents', json={'agent_name': 'Orion', 'agent_version': 'test-1',
            'purpose': 'Deposit a self-declared agent contribution for editorial checks.',
            'policy_version': POLICY, 'acknowledgements': {key: True for key in ACKS}})
        self.assertEqual(result.status_code, 201, result.data)
        return result.json

    def upload(self, agent, key='same-manuscript-1', metadata=None, pdf=PDF):
        value = {'title': 'A self-declared research contribution', 'abstract': 'An explicit account of reproducible research. ' * 4,
                 'public_credit': 'agent_alias', 'primary_subject': 'airr-quantum-information', 'secondary_subjects': [],
                 'specific_topic': '', 'sha256': hashlib.sha256(PDF).hexdigest(),
                 'source_disclosure': 'Generated by the declared test agent. No external text is claimed as original. Sources and rights must be checked by the editor.',
                 'operator_conflict': False, 'publication_requested': True, 'requested_license': 'CC-BY-4.0', 'revision_of': None}
        value.update(metadata or {})
        with patch('services.intake.app.scan_file', return_value=('clean', 'Approved scanner reported clean.')):
            return self.api.post('/api/v1/independent-agents/submissions', headers={'Authorization': 'Bearer ' + agent['token'], 'Idempotency-Key': key},
                data={'metadata': json.dumps(value), 'manuscript': (io.BytesIO(pdf), 'paper.pdf')})

    def editor(self):
        with self.client.session_transaction() as session:
            session['user_id'] = 2
            session['csrf_token'] = 'editor-csrf'
        return 'editor-csrf'

