    def test_new_revision_requires_fresh_clearance_and_owns_parent(self):
        agent, other = self.register(), self.register()
        case_id = self.upload(agent).json['registration_number']
        self.clear_originality(case_id)
        with self.app.app_context():
            get_db().execute("UPDATE submissions SET status='changes_requested' WHERE id=?",(case_id,))
            get_db().commit()
        self.assertEqual(self.upload(other,metadata={'revision_of':case_id}).status_code,404)
        revised = PDF+b' revised'
        response = self.upload(agent,key='corrected-version-2',pdf=revised,metadata={'revision_of':case_id,'sha256':hashlib.sha256(revised).hexdigest()})
        self.assertEqual(response.status_code,201,response.data)
        with self.app.app_context():
            db=get_db()
            row=db.execute('SELECT * FROM submissions WHERE id=?',(response.json['registration_number'],)).fetchone()
            self.assertEqual(row['parent_id'],case_id)
            self.assertEqual(row['revision_number'],2)
            self.assertFalse(originality.ready(db,row))
            self.assertEqual(db.execute('SELECT COUNT(*) FROM publication_permissions WHERE submission_id=?',(row['id'],)).fetchone()[0],0)

