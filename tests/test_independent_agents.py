    def test_case_actions_plan_scope_and_independent_appeal(self):
        agent=self.register()
        case_id=self.upload(agent,metadata={'publication_requested':False}).json['registration_number']
        path='/api/v1/independent-agents/cases/'+case_id+'/actions'
        headers={'Authorization':'Bearer '+agent['token']}
        def act(value):
            return self.api.post(path,headers=headers,json=value)
        self.assertEqual(act({'action':'publish'}).status_code,400)
        self.assertEqual(act({'action':'reply','body':'A private response supplying more evidence for this paper.'}).status_code,200)
        self.assertEqual(act({'action':'request_publication','sha256':hashlib.sha256(PDF).hexdigest(),'requested_license':'CC-BY-4.0'}).status_code,200)
        with self.app.app_context():
            db=get_db()
            plan=db.execute('INSERT INTO assessment_plans(submission_id,manuscript_sha256,providers_json,notice,created_by,created_at) VALUES(?,?,?,?,?,?)',
                (case_id,hashlib.sha256(PDF).hexdigest(),'[{"provider":"fixture","model_id":"fixture"}]','A synthetic named provider plan and safeguards for this exact test PDF.',2,iso()))
            plan_id=plan.lastrowid
            db.commit()
        approval={'action':'authorize_plan','plan_id':plan_id,'sha256':hashlib.sha256(PDF).hexdigest(),'confirm':True}
        self.assertEqual(act(approval).status_code,409)
        self.clear_originality(case_id)
        self.assertEqual(act({**approval,'sha256':'0'*64}).status_code,409)
        self.assertEqual(act(approval).status_code,200)
        with self.app.app_context():
            db=get_db()
            db.execute("UPDATE submissions SET status='declined',decided_at=?,decision_by=2 WHERE id=?",(iso(),case_id))
            db.commit()
        self.assertEqual(act({'action':'appeal','body':'A specific evidenced challenge to this synthetic test decision.'}).status_code,200)
        self.assertEqual(act({'action':'appeal','body':'A second appeal must not replace the first evidenced challenge.'}).status_code,409)
        with self.app.app_context():
            self.assertEqual(get_db().execute('SELECT status FROM submissions WHERE id=?',(case_id,)).fetchone()[0],'appeal_pending')
            self.assertEqual(get_db().execute('SELECT COUNT(*) FROM publication_permissions').fetchone()[0],0)


