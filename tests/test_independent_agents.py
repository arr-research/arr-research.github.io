    def test_all_release_paths_block_until_evidenced_exact_hash_review(self):
        agent = self.register()
        case_id = self.upload(agent).json['registration_number']
        csrf = self.editor()
        url = '/admin/submission/' + case_id
        self.assertEqual(self.client.get(url).status_code, 200)
        self.assertEqual(self.client.get(url + '/release-package').status_code, 409)
        form = {'csrf_token': csrf, 'signed': 'on', 'sha256': hashlib.sha256(PDF).hexdigest(),
                'permission_evidence': 'Recorded inspectable distribution evidence for this test manuscript and license. This is a synthetic test record, not a real grant.'}
        self.assertEqual(self.client.post(url + '/agent-release', data=form).status_code, 409)
        with self.app.app_context():
            db = get_db()
            scan = db.execute('INSERT INTO originality_scans(submission_id,manuscript_sha256,result_json,created_by,created_at) VALUES(?,?,?,?,?)',
                              (case_id, form['sha256'], '{}', 2, iso()))
            scan_id = scan.lastrowid
            db.commit()
        evidence = {k: 'Documented synthetic test evidence covering this check in full.' for k in
                    ('search_scope', 'match_adjudication', 'attribution_basis', 'rights_basis', 'privacy_check')}
        review = {**form, **evidence, 'sources_checked': 'https://example.org/source checked in this synthetic test; attribution was examined.', 'scan_id': str(scan_id), 'outcome': 'clear'}
        self.assertEqual(self.client.post(url + '/originality-review', data={**review, 'sha256': '0' * 64}).status_code, 409)
        self.assertEqual(self.client.post(url + '/originality-review', data=review).status_code, 302)
        # A permission accidentally issued through another workflow cannot stand
        # in for this route's evidenced human distribution decision.
        with self.app.app_context():
            db = get_db()
            db.execute('INSERT INTO publication_permissions VALUES(?,?,?,?)', (case_id, form['sha256'], 'CC-BY-4.0', iso()))
            db.commit()
        self.assertEqual(self.client.get(url + '/release-package').status_code, 409)
        with self.app.app_context():
            get_db().execute('DELETE FROM publication_permissions WHERE submission_id=?', (case_id,))
            get_db().commit()
        self.assertEqual(self.client.post(url + '/agent-release', data=form).status_code, 302)
        result = self.client.get(url + '/release-package')
        self.assertEqual(result.status_code, 200, result.data)
        self.assertEqual(result.json['public_status'], 'working_paper')
        self.assertEqual(result.json['originality_review']['manuscript_sha256'], form['sha256'])
        self.assertEqual(self.client.post(url + '/originality-review', data={**review, 'outcome': 'concerns'}).status_code, 302)
        self.assertEqual(self.client.get(url + '/release-package').status_code, 409)
        command = self.app.test_cli_runner().invoke(args=['mark-published', case_id, 'https://example.org/version'])
        self.assertNotEqual(command.exit_code, 0)

    def test_similarity_flags_reformatted_copy_without_automatic_verdict(self):
        corpus = Path(self.temp.name) / 'corpus' / 'ARR-TEST'
        corpus.mkdir(parents=True)
        prose = ' '.join('word' + str(i) for i in range(90))
        (corpus / 'paper.txt').write_text(prose)
        result = originality.compare_text(prose.upper().replace(' ', '\n'), corpus.parent)
        self.assertEqual(result['matches'][0]['candidate_sequence_overlap'], 1.0)
        self.assertIn('not a plagiarism verdict', result['scope'])
        with self.assertRaises(ValueError):
            originality.compare_text(prose, corpus / 'missing')

    def clear_originality(self, case_id):
        csrf = self.editor()
        corpus = Path(self.temp.name) / 'corpus' / 'public'
        corpus.mkdir(parents=True, exist_ok=True)
        prose = ' '.join('word' + str(i) for i in range(90))
        (corpus / 'paper.txt').write_text(prose)
        self.app.config['ORIGINALITY_CORPUS'] = str(corpus.parent)
        url = '/admin/submission/' + case_id
        with patch('services.intake.originality.extract_text', return_value=prose):
            result = self.client.post(url + '/originality-scan', data={'csrf_token': csrf})
        self.assertEqual(result.status_code, 302, result.data)
        with self.app.app_context():
            db = get_db()
            scan = db.execute('SELECT * FROM originality_scans WHERE submission_id=? ORDER BY id DESC LIMIT 1', (case_id,)).fetchone()
            self.assertFalse(originality.ready(db, db.execute('SELECT * FROM submissions WHERE id=?', (case_id,)).fetchone()))
            scan_id, sha = scan['id'], scan['manuscript_sha256']
        review = {'csrf_token': csrf, 'sha256': sha, 'scan_id': scan_id, 'outcome': 'clear', 'signed': 'on',
                  **{k: 'Documented synthetic test evidence, not a real scientific or rights determination.' for k in
                    ('search_scope', 'match_adjudication', 'attribution_basis', 'rights_basis', 'privacy_check')},
                  'sources_checked': 'https://example.org/source is the synthetic source for this fixture.'}
        self.assertEqual(self.client.post(url + '/originality-review', data=review).status_code, 302)
        return review

    def test_anonymous_handoff_hides_identity_and_new_scan_invalidates_clearance(self):
        agent = self.register()
        case_id = self.upload(agent, metadata={'public_credit':'anonymous'}).json['registration_number']
        review = self.clear_originality(case_id)
        url = '/admin/submission/' + case_id
        self.assertEqual(self.client.post(url + '/agent-release', data={**review,
            'permission_evidence':'Inspectable synthetic rights evidence covers this PDF and requested license. This is a test, not an actual authorization.'}).status_code,302)
        handoff = self.client.get(url + '/release-package').json
        self.assertEqual(handoff['authors'], 'Anonymous')
        self.assertNotIn('Orion', json.dumps(handoff))
        self.assertNotIn(agent['agent_id'], json.dumps(handoff))
        self.assertNotIn('version', handoff['agent_provenance'])
        self.assertIs(handoff['agent_provenance']['identity_verified'], False)
        with patch('services.intake.originality.extract_text', return_value=' '.join('word' + str(i) for i in range(90))):
            self.assertEqual(self.client.post(url + '/originality-scan', data={'csrf_token': review['csrf_token']}).status_code,302)
        self.assertEqual(self.client.get(url + '/release-package').status_code,409)
        self.assertEqual(self.client.post(url + '/originality-review',data=review).status_code,409)

