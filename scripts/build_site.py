def ranked_submit_papers(papers: list, metrics: dict) -> tuple[list, str, str]:
    research = [paper for paper in papers if paper.record_type == "research_paper"]
    use_views = bool(metrics.get("views", {}).get("available"))
    metric_key = "page_views" if use_views else "pdf_downloads"
    metric_label = "page views" if use_views else "PDF downloads"
    research.sort(
        key=lambda paper: (
            -(paper_activity(paper.id, metrics).get(metric_key) or 0),
            paper.metadata["title"].casefold(),
        )
    )
    return research, metric_key, metric_label


def build_submit(
    base: str,
    canonical_url: str,
    intake_url: str = "",
    papers: list | None = None,
    metrics: dict | None = None,
    author_lookup: dict[str, dict] | None = None,
    page_number: int = 1,
    assessments: list[dict] | None = None,
) -> str:
    metrics = metrics or {"views": {"available": False}, "papers": {}}
    assessments = assessments or []
    ranked, metric_key, metric_label = ranked_submit_papers(papers or [], metrics)
    page_size = 50
    page_count = max(1, (len(ranked) + page_size - 1) // page_size)
    if page_number < 1 or page_number > page_count:
        raise ValueError(f"Submit ranking page {page_number} is outside 1..{page_count}")
    start = (page_number - 1) * page_size
    page_papers = ranked[start : start + page_size]
    direct_action = (
        f'<a class="intake-link" href="{esc(intake_url.rstrip("/") + "/submit")}">Submit privately</a>'
        if intake_url
        else '<span class="intake-state">Private submission: opening soon</span>'
    )
    rows = []
    for rank, paper in enumerate(page_papers, start=start + 1):
        activity = paper_activity(paper.id, metrics)
        value = activity.get(metric_key) or 0
        authors = (
            author_links(paper.metadata, author_lookup, base)
            if author_lookup
            else esc(", ".join(author["name"] for author in paper.metadata["authors"]))
        )
        record_details = " · ".join(
            item
            for item in (
                paper.id,
                paper.version,
                paper.metadata.get("date", ""),
            )
            if item
        )
        keywords = " · ".join(paper.metadata.get("keywords", [])[:3])
        keywords_html = f'<span class="rank-keywords">{esc(keywords)}</span>' if keywords else ""
        rows.append(f"""
<li class="ranked-paper">
  <span class="rank-number">{rank:02d}</span>
  <div class="rank-paper-main"><span class="rank-record">{esc(record_details)}</span><h3><a href="{base}/{record_route(paper.metadata)}/{quote(paper.id)}/">{esc(paper.metadata['title'])}</a></h3><p>{authors}{keywords_html}</p><div class="rank-assessment">{assessment_badge(paper, assessments, f'{base}/{record_route(paper.metadata)}/{quote(paper.id)}/#model-assessments')}</div></div>
  <div class="rank-metric"><strong>{value:,}</strong><span>{esc(metric_label)}</span></div>
</li>""")
    if not rows:
        rows.append('<li class="ranked-paper empty"><div class="rank-paper-main"><h3>No public papers yet.</h3></div></li>')
    previous_link = (
        f'<a class="pager-link" rel="prev" href="{submit_page_url(base, page_number - 1)}">← Previous 50</a>'
        if page_number > 1
        else '<span></span>'
    )
    next_link = (
        f'<a class="pager-link next" rel="next" href="{submit_page_url(base, page_number + 1)}">Next 50 →</a>'
        if page_number < page_count
        else '<span></span>'
    )
    rank_explanation = (
        "Ordered by measured page views. Activity is not a scientific-quality score."
        if metric_key == "page_views"
        else "Page views are not yet measured, so this reproducible ranking uses canonical PDF downloads. Activity is not a scientific-quality score."
    )
    content = f"""
<section class="ranked-feed submit-index">
  <header><div><span>AIRR public catalogue · activity order</span><h1>Paper index</h1></div><div class="submit-tools">{direct_action}<a href="{base}/agents/">Submit with an agent</a><a href="{base}/subjects/">Choose a subject</a><a href="{base}/terms/">Terms</a><a href="{base}/privacy/">Privacy</a></div></header>
  <p class="subject-selection" data-selected-subject data-intake-url="{esc(intake_url)}" data-vocabulary-url="{base}/assets/subjects.json" hidden></p>
  <script src="{base}/assets/subject-selection.js" defer></script>
  {search_form(base)}
  <div class="compact-gate"><strong>New-admission gate</strong><span>operator-selected frontier audit</span><span>exact-version evidence</span><span>0 unresolved material objections</span><span>human decision</span><a href="{base}/assessments/">evidence and scores →</a></div>
  <div class="index-meta"><p>{esc(rank_explanation)}</p><span>Records {start + 1 if ranked else 0}–{min(start + page_size, len(ranked))} / {len(ranked)}</span></div>
  <div class="rank-columns" aria-hidden="true"><span>Rank</span><span>Record</span><span>Activity</span></div>
  <ol class="ranked-list" start="{start + 1}">{''.join(rows)}</ol>
  <nav class="pagination" aria-label="Paper ranking pages">{previous_link}<span>Page {page_number} of {page_count}</span>{next_link}</nav>
</section>
"""
    canonical = (
        f"{canonical_url}/submit/" if page_number == 1 else f"{canonical_url}/submit/page/{page_number}/"
    ) if canonical_url else ""
    title = "Submit and most-read papers — AIRR.SCIENCE" if page_number == 1 else f"Most-read papers, page {page_number} — AIRR.SCIENCE"
    return page_shell(title=title, description="Direct private submission and the paginated AIRR paper activity ranking.", content=content, base=base, canonical=canonical)


