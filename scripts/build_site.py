def papers_by_author(profiles: list[dict], papers: list) -> dict[str, list]:
    result = {profile["id"]: [] for profile in profiles}
    names = {profile["name"]: profile["id"] for profile in profiles}
    for profile in profiles:
        for alias in profile.get("aliases", []):
            names[alias] = profile["id"]
    for paper in papers:
        for author in paper.metadata["authors"]:
            result[names[author["name"]]].append(paper)
    return result


