def clean_base_path(value: str) -> str:
    value = value.strip()
    if not value or value == "/":
        return ""
    return "/" + value.strip("/")


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def disclosure_text(value: str) -> str:
    # Display the current archive name without rewriting preserved deposits or
    # altering identifiers. Abstracts and referee reports remain verbatim.
    return esc(re.sub(r"\bARR\b(?![-_])", "AIRR", value))


def exact_time(value: str) -> str:
    parsed = parse_exact_timestamp(value)
    offset = parsed.strftime("%z")
    zone = "UTC" if offset == "+0000" else f"UTC{offset[:3]}:{offset[3:]}"
    label = f"{parsed:%Y-%m-%d %H:%M:%S} {zone}"
    return f'<time datetime="{esc(value)}">{esc(label)}</time>'


def load_authors(papers: list) -> tuple[list[dict], dict[str, dict]]:
    value = json.loads(AUTHORS_FILE.read_text(encoding="utf-8"))
    profiles = value.get("authors") if isinstance(value, dict) else None
    if not isinstance(profiles, list):
        raise ValueError("registry/authors.json must contain an authors array")
    ids: set[str] = set()
    names: dict[str, dict] = {}
    for profile in profiles:
        if not isinstance(profile, dict) or not isinstance(profile.get("id"), str) or not profile["id"]:
            raise ValueError("Every author profile requires an id")
        if profile["id"] in ids:
            raise ValueError(f"Duplicate author id: {profile['id']}")
        ids.add(profile["id"])
        labels = [profile.get("name"), *profile.get("aliases", [])]
        for label in labels:
            if not isinstance(label, str) or not label.strip():
                raise ValueError(f"Author {profile['id']} has an invalid name or alias")
            if label in names:
                raise ValueError(f"Author name or alias is ambiguous: {label}")
            names[label] = profile
    missing = sorted(
        {
            author["name"]
            for paper in papers
            for author in paper.metadata["authors"]
            if author["name"] not in names
        }
    )
    if missing:
        raise ValueError(f"Missing stable author profiles: {', '.join(missing)}")
    return profiles, names


